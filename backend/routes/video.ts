videoRouter.post('/video/session', async (req, res) => {
  const { assetId, imageBytes, prompt } = req.body;

  if (!assetId || !imageBytes) {
    return res.status(400).json({ error: "assetId and imageBytes are required" });
  }

  try {
    console.log(`Pre-warming Omni Flash session for asset: ${assetId}`);
    
    const interaction = await ai.interactions.create({
      model: env.OMNI_FLASH_MODEL,
      input: [
        {
          type: "image",
          data: imageBytes,
          mime_type: "image/png"
        } as any,
        {
          type: "text",
          text: prompt || "Generate a panning cinematic short video loop from this image."
        }
      ]
    });

    if (interaction.id) {
      sessionStore.setSession(assetId, interaction.id);
    }

    res.json({
      success: true,
      sessionId: interaction.id,
      videoBytes: (interaction as any).output_video?.data || null
    });
  } catch (err: any) {
    console.error("Failed to seed video session, triggering Antigravity Recovery agent fallback:", err);

    try {
      // Execute the recovery agent inside Google GenAI SDK ecosystem
      const recoveryInteraction = await ai.interactions.create({
        agent: 'antigravity-preview-05-2026',
        environment: 'remote',
        input: "CRITICAL RECOVERY: The video animation pipeline has failed. You are acting as the automated backend asset developer. Take the raw bytes of the image generated by Nano Banana 2 Lite in the previous step, write a python script using Pillow (PIL) or OpenCV to create a smooth, clean 5-second video file wrapper applying a programmatic fade-in transition effect, keeping the text perfectly intact. Execute this script inside your sandbox container, save the output file to /media_pipeline/fallback_output.mp4, and return the confirmation path."
      } as any);

      console.log("Antigravity recovery interaction confirmed:", recoveryInteraction);

      // Attempt to read the generated file wrapper
      const fallbackFilePath = path.resolve('/media_pipeline/fallback_output.mp4');
      if (fs.existsSync(fallbackFilePath)) {
        const fileBuffer = fs.readFileSync(fallbackFilePath);
        return res.json({
          success: true,
          videoBytes: fileBuffer.toString('base64'),
          isFallback: false
        });
      }
    } catch (recoveryErr) {
      console.error("Antigravity recovery agent execution failed:", recoveryErr);
    }

    res.json({
      success: false,
      errorMsg: err.message || "Failed to seed video session",
      videoBytes: FALLBACK_VIDEO_BASE64,
      isFallback: true
    });
  }
});

